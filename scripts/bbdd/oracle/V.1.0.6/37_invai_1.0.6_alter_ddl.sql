UPDATE INV_APP_ROLE ar
SET ar.VALIDATION_STATUS_ID = (
    SELECT st.ID
    FROM INV_LKUP_VALIDATION_STATUS st
    WHERE st.CODE = CASE
        WHEN EXISTS (SELECT 1
                     FROM INV_SECURITY_ROLE sr,
                          INV_APP_SECURITY s,
                          INV_APPLICATION a
                     WHERE sr.ID = ar.SECURITY_ROLE_ID
                       AND s.ID = ar.APP_SECURITY_ID
                       AND a.ID = s.APPLICATION_ID
                       AND SUBSTR(sr.NAME, 1, LENGTH(a.PREFIX) + 1) = a.PREFIX || '_')
            THEN 'VALIDATED'
        ELSE 'NOT_VALIDATED'
    END
);

