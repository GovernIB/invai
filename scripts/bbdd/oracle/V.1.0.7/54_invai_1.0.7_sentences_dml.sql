-- Migration of the sections to categories (can't be run twice)
--   * The categories and subcategories that exist now are deleted.
--   * Every section becomes a category with the same names.
--   * The subcategories that were active are created again under the new categories:
--     Tècnica -> Desenvolupament, Seguretat -> Seguretat, Protecció de dades -> Dades,
--     any other category (Normativa, Contractació, the ones added by hand) -> General.
--   * The documents and links go to the category of their section; a document keeps its
--     subcategory only if it has a recreated one under that category.
--   * The roles get the permissions of their tab: INV_SUPER every category, INV_USER only General.

-- Old identifier (a section or a subcategory) -> identifier of the new category or subcategory
CREATE TABLE INV_TMP_CATEGORY_MAP
(
    KIND   VARCHAR2(10) NOT NULL,
    OLD_ID NUMBER(19)   NOT NULL,
    NEW_ID NUMBER(19)   NOT NULL
);

INSERT INTO INV_TMP_CATEGORY_MAP (KIND, OLD_ID, NEW_ID)
SELECT 'SECTION', s.ID, INV_DOCUMENT_CATEGORY_SEQ.nextval
FROM INV_LKUP_APP_SECTION s;

INSERT INTO INV_TMP_CATEGORY_MAP (KIND, OLD_ID, NEW_ID)
SELECT 'SUB', c.ID, INV_DOCUMENT_CATEGORY_SEQ.nextval
FROM INV_DOCUMENT_CATEGORY c
WHERE c.PARENT_ID IS NOT NULL AND c.DELETED_AT IS NULL;

-- The old categories are deactivated, so their names don't clash with the ones of the new categories
UPDATE INV_DOCUMENT_CATEGORY
SET DELETED_AT = SYSTIMESTAMP, DELETED_BY = 'ADMIN'
WHERE DELETED_AT IS NULL;

-- The new categories, from the sections
INSERT INTO INV_DOCUMENT_CATEGORY (ID, NAME, NAME_ES, PARENT_ID, CREATED_AT, CREATED_BY)
SELECT m.NEW_ID, s.NAME, s.NAME_ES, NULL, SYSTIMESTAMP, 'ADMIN'
FROM INV_TMP_CATEGORY_MAP m
JOIN INV_LKUP_APP_SECTION s ON s.ID = m.OLD_ID
WHERE m.KIND = 'SECTION';

-- The subcategories, created again under the new categories
INSERT INTO INV_DOCUMENT_CATEGORY (ID, NAME, NAME_ES, PARENT_ID, CREATED_AT, CREATED_BY)
SELECT m.NEW_ID, sc.NAME, sc.NAME_ES, pm.NEW_ID, SYSTIMESTAMP, 'ADMIN'
FROM INV_TMP_CATEGORY_MAP m
JOIN INV_DOCUMENT_CATEGORY sc ON sc.ID = m.OLD_ID
JOIN INV_DOCUMENT_CATEGORY oldp ON oldp.ID = sc.PARENT_ID
JOIN INV_LKUP_APP_SECTION s ON s.CODE = CASE oldp.NAME
                                           WHEN 'Tècnica' THEN 'DEVELOPMENT'
                                           WHEN 'Seguretat' THEN 'SECURITY'
                                           WHEN 'Protecció de dades' THEN 'DATA'
                                           ELSE 'GENERAL'
                                       END
JOIN INV_TMP_CATEGORY_MAP pm ON pm.KIND = 'SECTION' AND pm.OLD_ID = s.ID
WHERE m.KIND = 'SUB';

INSERT INTO INV_DOCUMENT_CATEGORY_AUD (AUDIT_ID, DOCUMENT_CATEGORY_ID, NAME, NAME_ES, PARENT_ID, CREATED_AT, CREATED_BY, AUD_ACTION, AUDIT_DATE, AUDIT_USER)
SELECT INV_DOCUMENT_CATEGORY_AUD_SEQ.nextval, c.ID, c.NAME, c.NAME_ES, c.PARENT_ID, c.CREATED_AT, c.CREATED_BY, 'INSERT', SYSTIMESTAMP, 'ADMIN'
FROM INV_DOCUMENT_CATEGORY c
WHERE c.ID IN (SELECT NEW_ID FROM INV_TMP_CATEGORY_MAP);

-- Documents: category from the section; subcategory only if it was recreated under that category.
-- The old category column is pointed at the new category so the old categories can be deleted.
UPDATE INV_APP_DOC_ATTACHMENT d
SET d.CATEGORY_ID = (SELECT m.NEW_ID FROM INV_TMP_CATEGORY_MAP m WHERE m.KIND = 'SECTION' AND m.OLD_ID = d.SECTION_ID),
    d.SUBCATEGORY_ID = (SELECT ms.NEW_ID
                        FROM INV_TMP_CATEGORY_MAP ms
                        JOIN INV_DOCUMENT_CATEGORY nc ON nc.ID = ms.NEW_ID
                        JOIN INV_TMP_CATEGORY_MAP mc ON mc.KIND = 'SECTION' AND mc.OLD_ID = d.SECTION_ID
                        WHERE ms.KIND = 'SUB' AND ms.OLD_ID = d.DOCUMENT_CATEGORY_ID AND nc.PARENT_ID = mc.NEW_ID),
    d.DOCUMENT_CATEGORY_ID = (SELECT m.NEW_ID FROM INV_TMP_CATEGORY_MAP m WHERE m.KIND = 'SECTION' AND m.OLD_ID = d.SECTION_ID);

UPDATE INV_APP_DOC_ATT_AUD d
SET d.CATEGORY_ID = (SELECT m.NEW_ID FROM INV_TMP_CATEGORY_MAP m WHERE m.KIND = 'SECTION' AND m.OLD_ID = d.SECTION_ID),
    d.SUBCATEGORY_ID = (SELECT ms.NEW_ID
                        FROM INV_TMP_CATEGORY_MAP ms
                        JOIN INV_DOCUMENT_CATEGORY nc ON nc.ID = ms.NEW_ID
                        JOIN INV_TMP_CATEGORY_MAP mc ON mc.KIND = 'SECTION' AND mc.OLD_ID = d.SECTION_ID
                        WHERE ms.KIND = 'SUB' AND ms.OLD_ID = d.DOCUMENT_CATEGORY_ID AND nc.PARENT_ID = mc.NEW_ID);

-- Links: category from the section
UPDATE INV_APP_LINK l
SET l.CATEGORY_ID = (SELECT m.NEW_ID FROM INV_TMP_CATEGORY_MAP m WHERE m.KIND = 'SECTION' AND m.OLD_ID = l.SECTION_ID);

UPDATE INV_APP_LINK_AUD l
SET l.CATEGORY_ID = (SELECT m.NEW_ID FROM INV_TMP_CATEGORY_MAP m WHERE m.KIND = 'SECTION' AND m.OLD_ID = l.SECTION_ID);

-- Documentation permissions of the roles: every permission on the categories of their tab,
-- INV_SUPER on all of them and INV_USER only on General
INSERT INTO INV_DOC_ROLE_PERM (ID, INV_ROLE_ID, DOCUMENT_CATEGORY_ID, CAN_READ, CAN_UPLOAD, CAN_EDIT, CAN_DELETE, CREATED_AT, CREATED_BY)
SELECT INV_DOC_ROLE_PERM_SEQ.nextval, r.ID, m.NEW_ID, 1, 1, 1, 1, SYSTIMESTAMP, 'ADMIN'
FROM (SELECT 'INV_USER' AS ROLE_NAME, 'GENERAL' AS SECTION_CODE FROM DUAL
      UNION ALL SELECT 'INV_SISTEMES', 'RESPONSIBLES' FROM DUAL
      UNION ALL SELECT 'INV_SISTEMES', 'SYSTEMS' FROM DUAL
      UNION ALL SELECT 'INV_SISTEMES', 'DATABASE' FROM DUAL
      UNION ALL SELECT 'INV_DESENVO', 'DEVELOPMENT' FROM DUAL
      UNION ALL SELECT 'INV_SEGURETAT', 'RESPONSIBLES' FROM DUAL
      UNION ALL SELECT 'INV_SEGURETAT', 'SECURITY' FROM DUAL
      UNION ALL SELECT 'INV_DADES', 'DATA' FROM DUAL
      UNION ALL SELECT 'INV_WS', 'INTEGRATIONS' FROM DUAL
      UNION ALL SELECT 'INV_ACCESIBILITAT', 'ACCESSIBILITY' FROM DUAL
      UNION ALL SELECT 'INV_SUPER', CODE FROM INV_LKUP_APP_SECTION) rs
JOIN (SELECT NAME, MIN(ID) AS ID FROM INV_ROLE GROUP BY NAME) r ON r.NAME = rs.ROLE_NAME
JOIN INV_LKUP_APP_SECTION s ON s.CODE = rs.SECTION_CODE
JOIN INV_TMP_CATEGORY_MAP m ON m.KIND = 'SECTION' AND m.OLD_ID = s.ID
WHERE NOT EXISTS (SELECT 1 FROM INV_DOC_ROLE_PERM p WHERE p.INV_ROLE_ID = r.ID AND p.DOCUMENT_CATEGORY_ID = m.NEW_ID);

INSERT INTO INV_DOC_ROLE_PERM_AUD (AUDIT_ID, DOC_ROLE_PERM_ID, INV_ROLE_ID, DOCUMENT_CATEGORY_ID, CAN_READ, CAN_UPLOAD, CAN_EDIT, CAN_DELETE, CREATED_AT, CREATED_BY, AUD_ACTION, AUDIT_DATE, AUDIT_USER)
SELECT INV_DOC_ROLE_PERM_AUD_SEQ.nextval, p.ID, p.INV_ROLE_ID, p.DOCUMENT_CATEGORY_ID, p.CAN_READ, p.CAN_UPLOAD, p.CAN_EDIT, p.CAN_DELETE, p.CREATED_AT, p.CREATED_BY, 'INSERT', SYSTIMESTAMP, 'ADMIN'
FROM INV_DOC_ROLE_PERM p
WHERE NOT EXISTS (SELECT 1 FROM INV_DOC_ROLE_PERM_AUD a WHERE a.DOC_ROLE_PERM_ID = p.ID AND a.AUD_ACTION = 'INSERT');

-- The old categories and subcategories go away, subcategories first
